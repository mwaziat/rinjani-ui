export const normalizeLocale = (locale?: string): RinjaniLocale => (
  locale?.toLowerCase().startsWith('id') ? 'id' : 'en'
)

export const mergeMessages = (
  base: RinjaniMessages,
  overrides?: DeepPartial<RinjaniMessages>,
): RinjaniMessages => ({
  ...base,
  ...(overrides ?? {}),
  common: { ...base.common, ...(overrides?.common ?? {}) },
  select: { ...base.select, ...(overrides?.select ?? {}) },
  autocomplete: { ...base.autocomplete, ...(overrides?.autocomplete ?? {}) },
  multiTagInput: { ...base.multiTagInput, ...(overrides?.multiTagInput ?? {}) },
  dataTable: { ...base.dataTable, ...(overrides?.dataTable ?? {}) },
  editDataTable: { ...base.editDataTable, ...(overrides?.editDataTable ?? {}) },
  tree: { ...base.tree, ...(overrides?.tree ?? {}) },
  dropzone: { ...base.dropzone, ...(overrides?.dropzone ?? {}) },
  alert: { ...base.alert, ...(overrides?.alert ?? {}) },
  toast: { ...base.toast, ...(overrides?.toast ?? {}) },
})
